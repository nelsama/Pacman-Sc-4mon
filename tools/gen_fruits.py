#!/usr/bin/env python3
# Convierte las matrices 8x8 de frutas (colores ARGB) a 2 planos de bits por
# fila, para vc_load_spr_pattern(spr, plan0, plan1).
#
# Mapeo de colores -> indice de paleta (1..3):
#   transparente (0x00000000) -> indice 0 (no se pinta)
#   0xff0bbc00 (verde)        -> indice 1
#   0xff0000ff (rojo)         -> indice 2
#   0xff07b3ff (naranja)      -> indice 3
# index = (plan1_bit << 1) | plan0_bit ; el color sale de la paleta elegida
# en FLAGS del sprite.

GREEN  = 0xff0bbc00
RED    = 0xff0000ff
ORANGE = 0xff07b3ff

def idx_of(v):
    if v == 0:          return 0
    if v == GREEN:      return 1
    if v == RED:        return 2
    if v == ORANGE:     return 3
    raise ValueError("color desconocido: %08x" % v)

def to_planes(rows):
    # rows: lista de 8 filas, cada una 8 valores.
    plan0 = []
    plan1 = []
    for r in rows:
        if len(r) != 8:
            raise ValueError("fila no tiene 8 px")
        b0 = 0
        b1 = 0
        for c, v in enumerate(r):
            idx = idx_of(v)
            bit = 7 - c  # bit 7 = pixel izquierdo
            if idx & 1: b0 |= (1 << bit)
            if idx & 2: b1 |= (1 << bit)
        plan0.append(b0)
        plan1.append(b1)
    return plan0, plan1

def fmt(name, plan):
    body = ",".join("0x%02X" % b for b in plan)
    return "static const uint8_t %s[8] = { %s };" % (name, body)

